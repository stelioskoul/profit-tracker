import { build } from "esbuild";
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const out = join(root, ".vercel/output");
const marker = join(out, ".profit-tracker-generated");
try {
  await stat(out);
  if (await readFile(marker, "utf8") !== "Generated by scripts/build-vercel-output.mjs\n") {
    throw new Error(`Refusing to replace unrecognized build output: ${out}`);
  }
  await rm(out, { recursive: true });
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
const functionDir = join(out, "functions/index.func");
await mkdir(functionDir, { recursive: true });
await writeFile(marker, "Generated by scripts/build-vercel-output.mjs\n");
await cp(join(root, "dist/public"), join(out, "static"), { recursive: true });
await build({
  entryPoints: [join(root, "vercel/server.ts")],
  outfile: join(functionDir, "server.cjs"),
  bundle: true,
  platform: "node",
  format: "cjs",
  footer: { js: "module.exports = module.exports.default;" },
  target: "node24",
  packages: "bundle",
  loader: { ".html": "text" },
  logLevel: "warning",
});
await writeFile(join(functionDir, ".vc-config.json"), JSON.stringify({
  runtime: "nodejs24.x",
  handler: "server.cjs",
  launcherType: "Nodejs",
  shouldAddHelpers: false,
  maxDuration: 300,
}, null, 2) + "\n");
await writeFile(join(out, "config.json"), JSON.stringify({
  version: 3,
  routes: [{ handle: "filesystem" }, { src: "/.*", dest: "/index" }],
}, null, 2) + "\n");
console.log(`Vercel Build Output ready: ${out}`);
